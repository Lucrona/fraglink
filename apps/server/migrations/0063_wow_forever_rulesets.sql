-- Forever has no realms: players pick a ruleset, and each region has one
-- megaserver per ruleset. This reference table is seed-only.
-- No wow_characters / hour backfill or rewrites; ruleset_id stays null
-- until a later lookup fills it.
--
-- Sources (checked 11 Nov 2026):
--   Blizzard, "Choose Your Ruleset in World of Warcraft: Forever"
--     https://news.blizzard.com/en-us/article/24302070/choose-your-ruleset-in-world-of-warcraft-forever
--   Battle.net Game Data: GET /data/wow/ruleset/index
--     namespace dynamic-forever-us / dynamic-forever-eu
--     (the realm and connected-realm indexes are 404; rulesets replaced them)
--   Character profiles carry ruleset {id, name} and no realm object.
-- Official names and ids: 1 PvP, 2 Normal, 3 Roleplay, 15 Roleplay PvP
-- on US and EU. Verified 11 Nov 2026 with client-credentials GETs of
-- /data/wow/ruleset/index and /data/wow/ruleset/{id} (en_US names).
-- IDs 4-14 and 16 returned 404. Hardcore is announced for after launch
-- and is not in the index yet, so it is not seeded.
CREATE TABLE IF NOT EXISTS wow_forever_rulesets (
    id            integer GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    region        text NOT NULL CHECK (region IN ('us', 'eu')),
    blizzard_id   integer NOT NULL,
    slug          text NOT NULL,
    name          text NOT NULL,
    ruleset_type  text NOT NULL CHECK (ruleset_type IN ('normal', 'pvp', 'roleplay', 'roleplay_pvp')),
    UNIQUE (region, blizzard_id),
    UNIQUE (region, slug)
);

INSERT INTO wow_forever_rulesets (region, blizzard_id, slug, name, ruleset_type) VALUES
    ('us',  1, 'pvp',          'PvP',          'pvp'),
    ('us',  2, 'normal',       'Normal',       'normal'),
    ('us',  3, 'roleplay',     'Roleplay',     'roleplay'),
    ('us', 15, 'roleplay-pvp', 'Roleplay PvP', 'roleplay_pvp'),
    ('eu',  1, 'pvp',          'PvP',          'pvp'),
    ('eu',  2, 'normal',       'Normal',       'normal'),
    ('eu',  3, 'roleplay',     'Roleplay',     'roleplay'),
    ('eu', 15, 'roleplay-pvp', 'Roleplay PvP', 'roleplay_pvp')
ON CONFLICT (region, blizzard_id) DO NOTHING;

ALTER TABLE wow_characters
    ADD COLUMN IF NOT EXISTS ruleset_id integer REFERENCES wow_forever_rulesets(id);

CREATE INDEX IF NOT EXISTS wow_characters_ruleset
    ON wow_characters (ruleset_id) WHERE ruleset_id IS NOT NULL;

ALTER TABLE bnet_characters
    ADD COLUMN IF NOT EXISTS ruleset_blizzard_id integer;
